export const VENDOR_RULES = {
  minPrice: 15000,
  maxPrice: 100000,
  mmrTolerancePct: 0.06, // ±6%
};

export function formatCurrency(amount: number | null | undefined): string {
  if (amount === null || amount === undefined || isNaN(amount)) return 'N/A';
  return '$' + amount.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 0 });
}

export function formatNumber(num: number | null | undefined): string {
  if (num === null || num === undefined || isNaN(num)) return 'N/A';
  return num.toLocaleString('en-US');
}

export function validatePrice(
  priceNum: number,
  vehicle: Vehicle,
  vendorRules = VENDOR_RULES
): { status: 'ok' | 'warning' | 'error'; message: string; minMmr: number; maxMmr: number } {
  const benchmarkMmr = vehicle.marketPricing.condAdjMmr || vehicle.marketPricing.mmr;
  const minMmr = Math.round(benchmarkMmr * (1 - vendorRules.mmrTolerancePct));
  const maxMmr = Math.round(benchmarkMmr * (1 + vendorRules.mmrTolerancePct));

  if (priceNum <= 0) {
    return {
      status: 'error',
      message: 'Price must be greater than $0.',
      minMmr,
      maxMmr,
    };
  }

  if (priceNum < vendorRules.minPrice) {
    return {
      status: 'error',
      message: `Price $${priceNum.toLocaleString()} is below vendor lower limit of $${vendorRules.minPrice.toLocaleString()}.`,
      minMmr,
      maxMmr,
    };
  }

  if (priceNum > vendorRules.maxPrice) {
    return {
      status: 'error',
      message: `Price $${priceNum.toLocaleString()} exceeds vendor maximum limit of $${vendorRules.maxPrice.toLocaleString()}.`,
      minMmr,
      maxMmr,
    };
  }

  // Warning if outside ±6% of Cond Adj MMR, UNLESS inspection is expired (per rule 4.5.3: "Skipped for expired-inspection vehicles")
  if (!vehicle.inspectionExpired) {
    if (priceNum < minMmr || priceNum > maxMmr) {
      return {
        status: 'warning',
        message: `$${priceNum.toLocaleString()} is outside ±6% of MMR $${benchmarkMmr.toLocaleString()} (allowed: $${minMmr.toLocaleString()} – $${maxMmr.toLocaleString()})`,
        minMmr,
        maxMmr,
      };
    }
  }

  return {
    status: 'ok',
    message: 'Vehicle has been modified',
    minMmr,
    maxMmr,
  };
}
